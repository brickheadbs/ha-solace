@dataclass(frozen=True, slots=True)
class Solution:
    """The engine's computed solution for one light."""

    level: int
    should_write: bool
    mode: Mode
    ambience_open: bool
    demand: float
    stops: float
    fraction: float
    source: str = "demand"
    state_table: StateTable | None = None
    trace: tuple[tuple[str, object], ...] = field(default=())

    def with_trace(self, step: str, value: object) -> Solution:
        return replace(self, trace=(*self.trace, (step, value)))
