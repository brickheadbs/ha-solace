class Family(str, Enum):
    """Bulb families with distinct Zigbee hardware rate and serialisation capabilities."""

    AQARA_RGB = "aqara_rgb"
    AQARA_CCT = "aqara_cct"
    IKEA = "ikea"


class Mode(str, Enum):
    """Engine operating modes."""

    NORMAL = "normal"
    NIGHT = "night"
    AWAY = "away"
    SUNRISE = "sunrise"
    SUNSET = "sunset"


