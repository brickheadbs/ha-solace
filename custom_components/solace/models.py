@dataclass(frozen=True, slots=True)
class MasterOutput:
    """The baseline generated by Master Processing before room/fixture post-processing."""

    target_brightness: int
    target_kelvin: int
    demand: float
    time_brightness_level: int
    cloud_coverage: float | None = None
    cloud_alpha: float = 0.0
    demand_clear: float = 0.0
    demand_cloudy: float = 0.0
    trace: tuple[tuple[str, object], ...] = field(default=())


@dataclass(frozen=True, slots=True)
class StateTable:
    """Pre-computed brightness & colour levels for all operating tiers."""

    l1: int
    """Occupancy active level (brightest automatic level)."""
    l2: int
    """Diminished subzone level (relative to L1 in stops)."""
    l3: int
    """Ambience resting floor (fixed level per room)."""
    ls: int
    """Housewide Night Mode level."""
    target_kelvin: int
    """Target colour temperature."""


